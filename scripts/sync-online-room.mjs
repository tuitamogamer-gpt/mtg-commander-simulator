// Keep the standalone room kernel identical to the browser's pure contract.
import fs from 'node:fs';
const browser = new URL('../src/modules/multiplayer.js', import.meta.url);
const target = new URL('../logic.js', import.meta.url);
const source = fs.readFileSync(browser, 'utf8');
const start = source.indexOf('  const PROTOCOL_VERSION');
const end = source.indexOf('  function cardToken');
if (start < 0 || end < start) throw new Error('Room contract boundaries are missing.');
const generated = '// Generated by scripts/sync-online-room.mjs from the pure browser room contract.\n' +
  source.slice(start, end).split('\n').map(line => line.replace(/^  /, '')).join('\n') +
  `
// Preserve the legacy platform adapter while sharing the entire room kernel.
const roomMeta = { game: meta().name, minPlayers: meta().minPlayers, maxPlayers: meta().maxPlayers };
const serverValidateAction = (state, playerId, action) => validateAction(state, action, playerId);
const serverApplyAction = (state, playerId, action) => applyAction(state, action, playerId);
const serverIsGameOver = state => {
  if (!isGameOver(state)) return { over: false };
  const seat = Number.isInteger(state.winnerSeat) ? state.seats[state.winnerSeat] : null;
  return { over: true, winner: seat?.playerId || \`seat:\${state.winnerSeat}\`, winnerSeat: state.winnerSeat };
};
export { roomMeta as meta, setup, serverValidateAction as validateAction, serverApplyAction as applyAction, serverIsGameOver as isGameOver, viewFor };
`;
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== generated) throw new Error('Run node scripts/sync-online-room.mjs before shipping a room protocol change.');
} else fs.writeFileSync(target, generated);
