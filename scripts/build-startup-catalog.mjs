// Builds what the page loads before setup opens.
//
// src/app.js lists every module and all Oracle batches; tools and tests load
// it as it is. A page does not need most of it to show the deck list: about
// four of five card definitions are used by no built-in deck, only by
// imported ones. This script writes, from src/app.js and the deck lists:
//
//   src/app-startup.js         the same modules, with each run of batch
//                              imports replaced by one startup part
//   src/oracle-startup/part-N.js  the cards of that run that built-in decks
//                              use, as `startupSubset` batches in batch order
//   src/oracle-catalog-full.js every batch, loaded when an imported deck
//                              needs the rest (MTG.ensureFullCatalog)
//
//   node scripts/build-startup-catalog.mjs --write   regenerate the files
//   node scripts/build-startup-catalog.mjs --check   fail if they are stale
//
// Run it after adding a deck or an Oracle batch. tests/startup-catalog.test.mjs
// fails while the files are stale.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { extractRawData } from './source-audit.mjs';

const defaultRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const BATCH_PREFIX = './oracle-batches/';
const REGISTER = 'MTG.registerOracleBatch(';
const HEADER = '// Generated by npm run build:startup (scripts/build-startup-catalog.mjs). Do not edit by hand.\n';

// Modules whose quoted card names are not references from a deck's script:
// the list of every selectable card name, the printing aliases, and the
// generic Oracle rule modules, which hold the rules of imported cards by name.
const isNameTable = specifier => /\/(?:oracle-v22-card-names|deck-card-aliases)\.js$/.test(specifier) ||
  /\/oracle-v\d[^/]*\.js$/.test(specifier);

export function readBatchModule(source, label = 'batch') {
  const start = source.indexOf(REGISTER), end = source.lastIndexOf(');');
  if (start < 0 || end < 0) throw new Error(`${label}: no ${REGISTER}...) call`);
  return JSON.parse(source.slice(start + REGISTER.length, end));
}

function quotedStrings(code) {
  const found = new Set();
  for (const match of code.matchAll(/'((?:[^'\\\n]|\\.){2,80})'|"((?:[^"\\\n]|\\.){2,80})"|`((?:[^`\\\n$]|\\.){2,80})`/g)) {
    found.add((match[1] ?? match[2] ?? match[3]).replace(/\\(['"`])/g, '$1'));
  }
  return found;
}

function stringValues(value, visit) {
  if (typeof value === 'string') visit(value);
  else if (Array.isArray(value)) for (const item of value) stringValues(item, visit);
  else if (value && typeof value === 'object') for (const item of Object.values(value)) stringValues(item, visit);
}

export function buildStartupCatalog({ root = defaultRoot } = {}) {
  const src = path.join(root, 'src');
  const appSource = fs.readFileSync(path.join(src, 'app.js'), 'utf8');
  const imports = [...appSource.matchAll(/^import ['"](.+?)['"];?[ \t]*$/gm)].map(match => match[1]);
  if (!imports.length) throw new Error('src/app.js has no imports.');
  const rawDB = extractRawData(fs.readFileSync(path.join(src, 'data.js'), 'utf8'));

  // Every batch card by name, and the batches in their import order.
  const batches = [], batchCards = new Map();
  for (const specifier of imports.filter(item => item.startsWith(BATCH_PREFIX))) {
    const batch = readBatchModule(fs.readFileSync(path.join(src, specifier), 'utf8'), specifier);
    batches.push({ specifier, batch });
    for (const entry of batch.cards) batchCards.set(entry.raw.name, entry);
  }

  // 1. The cards of the built-in decks.
  const startup = new Set();
  const need = name => { if (batchCards.has(name) && !startup.has(name)) { startup.add(name); return true; } return false; };
  for (const deck of rawDB.decks) {
    for (const row of deck.cards || []) need(row.name);
    for (const name of [deck.commander, deck.partner]) if (name) need(name);
  }
  const fromDecks = startup.size;
  // 2. Card names that a script module quotes: a manual script for the card,
  // a named token or copy. A word that is also a card name ("Exile") costs
  // one small definition; a missed name would be a card missing in a game.
  for (const specifier of imports) {
    if (specifier.startsWith(BATCH_PREFIX) || isNameTable(specifier)) continue;
    for (const text of quotedStrings(fs.readFileSync(path.join(src, specifier), 'utf8'))) need(text);
  }
  // 3. Card names inside the definitions that are loaded at startup, until
  // nothing new is found.
  stringValues(rawDB.cards, need);
  const scanned = new Set();
  for (let grew = true; grew;) {
    grew = false;
    for (const name of [...startup]) {
      if (scanned.has(name)) continue;
      scanned.add(name);
      stringValues(batchCards.get(name), text => { if (need(text)) grew = true; });
    }
  }

  // One startup part for each run of batch imports in src/app.js, in the
  // place of that run: scripts loaded before and after it see the same cards
  // in the same order as with the complete batches.
  const files = new Map(), startupImports = [];
  let run = [];
  const closeRun = () => {
    if (!run.length) return;
    const part = `./oracle-startup/part-${files.size + 1}.js`;
    const lines = [HEADER.trimEnd(),
      `// The cards of ${run.length} Oracle batch${run.length === 1 ? '' : 'es'} that built-in decks use, in batch order.`,
      "'use strict';", 'var MTG = globalThis.MTG || (globalThis.MTG = {});',
      // The place of this run among the modules, for the batches that follow later.
      `MTG.beginOracleCompileStage(${JSON.stringify(run.map(row => row.batch.id))});`];
    for (const { batch } of run) {
      const cards = batch.cards.filter(entry => startup.has(entry.raw.name));
      if (cards.length) lines.push(`${REGISTER}${JSON.stringify({ ...batch, startupSubset: true, cards })});`);
    }
    files.set(part, lines.join('\n') + '\n');
    startupImports.push(part);
    run = [];
  };
  const byModule = new Map(batches.map(row => [row.specifier, row]));
  for (const specifier of imports) {
    if (byModule.has(specifier)) { run.push(byModule.get(specifier)); continue; }
    closeRun();
    startupImports.push(specifier);
  }
  closeRun();

  const output = new Map();
  output.set('src/app-startup.js', HEADER +
    '// What the page loads before setup opens: src/app.js with each run of Oracle\n' +
    '// batches replaced by the cards of it that built-in decks use.\n' +
    startupImports.map(specifier => `import '${specifier}';`).join('\n') + '\n');
  for (const [part, source] of files) output.set(path.posix.join('src', part), source);
  output.set('src/oracle-catalog-full.js', HEADER +
    '// Every Oracle batch of src/app.js, in its order. Loaded when an imported deck\n' +
    '// needs the cards that built-in decks do not use (MTG.ensureFullCatalog).\n' +
    batches.map(row => `import '${row.specifier}';`).join('\n') + '\n');

  return {
    output,
    summary: {
      batches: batches.length, batchCards: batchCards.size, startupCards: startup.size, fromDecks,
      deferredCards: batchCards.size - startup.size, parts: files.size,
      startupBytes: [...files.values()].reduce((sum, source) => sum + Buffer.byteLength(source), 0),
    },
  };
}

// The generated files that differ from what the sources now give.
export function staleStartupCatalog({ root = defaultRoot } = {}) {
  const { output } = buildStartupCatalog({ root });
  const stale = [];
  for (const [file, source] of output) {
    const target = path.join(root, file);
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== source) stale.push(file);
  }
  const directory = path.join(root, 'src', 'oracle-startup');
  if (fs.existsSync(directory)) {
    for (const name of fs.readdirSync(directory)) {
      if (!output.has(path.posix.join('src/oracle-startup', name))) stale.push(`src/oracle-startup/${name} (no longer generated)`);
    }
  }
  return stale;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { output, summary } = buildStartupCatalog();
  if (process.argv.includes('--write')) {
    fs.mkdirSync(path.join(defaultRoot, 'src', 'oracle-startup'), { recursive: true });
    for (const name of fs.readdirSync(path.join(defaultRoot, 'src', 'oracle-startup'))) {
      if (!output.has(path.posix.join('src/oracle-startup', name))) fs.unlinkSync(path.join(defaultRoot, 'src', 'oracle-startup', name));
    }
    for (const [file, source] of output) fs.writeFileSync(path.join(defaultRoot, file), source);
    console.log(`Startup catalog written: ${summary.startupCards} of ${summary.batchCards} batch cards ` +
      `(${summary.fromDecks} from decks) in ${summary.parts} parts, ${(summary.startupBytes / 1e6).toFixed(1)} MB; ` +
      `${summary.deferredCards} cards load on demand.`);
  } else if (process.argv.includes('--check')) {
    const stale = staleStartupCatalog();
    if (stale.length) {
      console.error('Stale startup catalog. Run: npm run build:startup\n  ' + stale.join('\n  '));
      process.exit(1);
    }
    console.log('Startup catalog is current.');
  } else {
    console.log(JSON.stringify(summary, null, 2));
  }
}
